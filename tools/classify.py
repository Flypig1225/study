def all_topics():
    return CRIMINAL + CIVIL


QUOTE = re.compile(r'《[^》]{2,40}》[^。]{0,20}?规定[::]?')


def strip_law(text):
    """去掉法条原文引用与法定刑表述，降低对板块判断的干扰。"""
    text = QUOTE.sub(" ", text)
    text = re.sub(r'第[一二三四五六七八九十百零\d]+条', " ", text)
    text = re.sub(r'处[^,。;]{0,15}?(有期徒刑|拘役|管制|罚金|无期徒刑|死刑)', " ", text)
    text = re.sub(r'(判处|宣告)[^,。;]{0,10}?(有期徒刑|拘役|管制)', " ", text)
    return text


def tag(text, subject):
    lexicon = CRIMINAL if subject == "刑法" else CIVIL
    hits = []
    for node, kws in lexicon:
        for kw in kws:
            if kw in text:
                hits.append((node, kw))
                break
    return hits


def main():
    qs = json.load(open(os.path.join(ROOT, "data", "questions.json"), encoding="utf-8"))
    overrides = {}
    op = os.path.join(ROOT, "data", "node_overrides.json")
    if os.path.exists(op):
        for k, v in json.load(open(op, encoding="utf-8")).items():
            overrides[k] = v

    out, unmatched = [], defaultdict(list)
    for q in qs:
        text = strip_law(q["stem"]) + " " + strip_law(" ".join(q["options"].values()))
        key = f"{q['year']}-{q['num']}"
        if key in overrides:
            q["node"] = overrides[key]
            q["hit"] = "manual"
        else:
            hits = tag(text, q["subject"])
            if hits:
                q["node"], q["hit"] = hits[0]
            else:
                q["node"], q["hit"] = "未分类", ""
        if q["node"] == "未分类":
            unmatched[q["subject"]].append(q)
        out.append(q)

    json.dump(out, open(os.path.join(ROOT, "data", "tagged.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)

    for subj in ("刑法", "民法"):
        c = Counter(q["node"] for q in out if q["subject"] == subj)
        tot = sum(q["score"] for q in out if q["subject"] == subj)
        print(f"\n=== {subj} (总 {tot} 分) ===")
        for node, n in c.most_common():
            sc = sum(q["score"] for q in out if q["subject"] == subj and q["node"] == node)
            print(f"  {node:22} {n:4} 题  {sc:5} 分")
        print(f"  未分类 {len(unmatched[subj])} 题")
        for q in unmatched[subj][:12]:
            print(f"    {q['year']}-{q['num']:2} {q['type'][:2]} {q['stem'][:50]}")


if __name__ == "__main__":
    main()

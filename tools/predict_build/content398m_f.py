def appendix_a(tagged_path, th, S):
    st = []
    st.append(P('附录 A · 22 年（2005–2026）398 主观题逐题索引', S['h1']))
    st.append(P('数据自动生成自 data/tagged.json（1,302 题 → 202 道主观题）：题号／学科／板块／命中点。用于最后一轮"过真题"查漏补缺——凡背过的要能口述；没背过的落到 S/A 档清单里。', S['small']))
    rows_raw = json.load(open(tagged_path))
    types = ('简答', '辨析', '法条分析', '案例分析')
    items = [q for q in rows_raw if q.get('type') in types]
    items.sort(key=lambda q: (q['year'], q['num']))
    type_short = {'简答': '简', '辨析': '辨', '法条分析': '法', '案例分析': '例'}
    rows = []
    for q in items:
        rows.append((str(q['year']), str(q['num']), q.get('subject', '')[0], type_short.get(q['type'], q['type'][:1]),
                     q.get('node', ''), q.get('hit', '')))
    st.append(table(['年', '号', '科', '型', '考察板块', '命中点'], rows,
                    [14*mm, 12*mm, 9*mm, 9*mm, 66*mm, 68*mm], th.accent, S))
    st.append(P('类型缩写：简＝简答 · 辨＝辨析（2018 取消）· 法＝法条分析 · 例＝案例分析；科：刑／民。', S['small']))
    return st


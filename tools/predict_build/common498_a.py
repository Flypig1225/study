def _mk(S, tag, no, title, where, why, points, stem, rubric):
    flow = []
    flow.append(KeepTogether([
        P(f'{tag} {no}. {title}', S['h2']),
        P(f'<font color="#0F4C3A">▶ 预测方位：</font>{where}；<font color="#0F4C3A">定位依据：</font>{why}', S['card']),
        P('【核心背诵踩分点】', S['h3']),
    ]))
    for i, p in enumerate(points, 1):
        flow.append(P(f'{i}. {p}', S['bodyL']))
    flow.append(P('【2027 预测模拟大题】', S['h3']))
    flow.append(P(stem, S['quote']))
    flow.append(P('【参考答案与评分拆解】', S['h3']))
    for i, p in enumerate(rubric, 1):
        flow.append(P(f'{i}）{p}', S['bodyL']))
    return flow


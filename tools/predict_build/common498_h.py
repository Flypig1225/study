def appendix_a(tagged_path, th, S):
    st = []
    st.append(P('附录 A · 22 年（2005–2026）498 主观题逐题索引', S['h1']))
    st.append(P('数据自动生成自 data/zonghe/tagged.json（1,433 题 → 163 道主观题：简答 66＋材料分析 66＋论述 31）。题号／学科／板块／命中点。背完第三部分后用此表查漏补缺。', S['small']))
    rows_raw = json.load(open(tagged_path))
    items = [q for q in rows_raw if q.get('type') in ('简答', '分析', '论述')]
    items.sort(key=lambda q: (q['year'], q['num']))
    type_short = {'简答': '简', '分析': '析', '论述': '论'}
    subj_short = {'法理学': '理', '中国宪法学': '宪', '中国法制史': '史'}
    rows = []
    for q in items:
        rows.append((str(q['year']), str(q['num']), subj_short.get(q.get('subject'), (q.get('subject') or '?')[:1]),
                     type_short.get(q['type'], q['type'][:1]),
                     q.get('node', ''), q.get('hit', '')))
    st.append(table(['年', '号', '科', '型', '考察板块', '命中点'], rows,
                    [14*mm, 12*mm, 9*mm, 9*mm, 62*mm, 74*mm], th.accent, S))
    st.append(P('类型缩写：简＝简答（#51–#53）· 析＝材料分析（#54–#56）· 论＝论述（#57–#58）；科：理（法理学）／宪（中国宪法学）／史（中国法制史）。', S['small']))
    return st


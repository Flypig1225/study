def wrap(text, size, width, font="china-s"):
    lines = []
    cur = ""
    for ch in text:
        t = cur + ch
        if tlen(t, size, font) > width:
            lines.append(cur); cur = ch
        else:
            cur = t
    if cur: lines.append(cur)
    return lines


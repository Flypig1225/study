def compute_unit_prediction(subject, node, qs_meta):
    """Compute 2027 predicted score & metadata for a unit.

    Args:
        subject: 科目名称
        node: 章节板块名称
        qs_meta: iterable of dicts/tuples having year (int) and score (float/int)
    Returns:
        dict with keys: w (2027 predicted weight), w5 (recent 5y avg),
        wh (22y avg), bt (short badge), pt (short reason)
    """
    all_s = r9_s = r5_s = old_s = 0.0
    for q in qs_meta:
        y = q["y"] if "y" in q else q["year"]
        sc = q.get("sc")
        if sc is None:
            sc = q.get("score")
        if sc is None:
            sc = 1.0 if q.get("t") == "单" or q.get("type") == "单项选择" else 2.0
        all_s += sc
        if y >= 2022:
            r5_s += sc
        if y >= 2018:
            r9_s += sc
        else:
            old_s += sc

    wh = all_s / 22.0
    r9 = r9_s / 9.0
    r5 = r5_s / 5.0
    old = old_s / 13.0

    base = 0.55 * r5 + 0.30 * r9 + 0.15 * wh
    trend = max(-0.35, min(0.45, 0.25 * (r5 - old)))
    boost, badge, reason = PRED_META.get((subject, node), (0.0, "", ""))
    pw = round(max(0.3, base + trend + boost), 1)
    return {
        "w": pw,
        "w5": round(r5, 1),
        "wh": round(wh, 1),
        "bt": badge,
        "pt": reason,
    }

def years_for(text_of, lexicon):
    out = {}
    for name, kws in lexicon.items():
        ys = sorted({y for y, t in text_of.items() if any(k in t for k in kws)})
        out[name] = ys
    return out


def main():
    qs = json.load(open(os.path.join(ROOT, "data", "tagged.json"), encoding="utf-8"))
    years = sorted({q["year"] for q in qs})
    report = {}
    for subj, lexicon in (("刑法", CRIMINAL), ("民法", CIVIL)):
        obj_text, subj_text = defaultdict(str), defaultdict(str)
        for q in qs:
            if q["subject"] != subj:
                continue
            blob = q["stem"] + " " + " ".join(q["options"].values())
            if q["type"] in ("单项选择", "多项选择"):
                obj_text[q["year"]] += " " + blob
            else:
                subj_text[q["year"]] += " " + blob
        obj = years_for(obj_text, lexicon)
        sub = years_for(subj_text, lexicon)

        # 重复率检验：出现在选择题中的考点，其次年是否再次出现
        nxt_total = nxt_hit = 0
        gaps = []
        for name, ys in obj.items():
            for y in ys:
                if y + 1 in years:
                    nxt_total += 1
                    if y + 1 in ys:
                        nxt_hit += 1
            for a, b in zip(ys, ys[1:]):
                gaps.append(b - a)
        report[subj] = {
            "obj": obj, "sub": sub,
            "n_points": len(lexicon),
            "obj_multi": sum(1 for ys in obj.values() if len(ys) >= 2),
            "obj_mean_years": statistics.mean([len(ys) for ys in obj.values()]),
            "next_year_rate": nxt_hit / nxt_total if nxt_total else 0,
            "median_gap": statistics.median(gaps) if gaps else 0,
            "mean_gap": round(statistics.mean(gaps), 1) if gaps else 0,
        }

    for subj in ("刑法", "民法"):
        r = report[subj]
        print(f"=== {subj} ===")
        print(f"考点数 {r['n_points']}；出现在选择题里 ≥2 个年份的考点 {r['obj_multi']} 个"
              f"（{r['obj_multi']/r['n_points']*100:.0f}%）")
        print(f"平均每个考点出现 {r['obj_mean_years']:.1f} 个年份")
        print(f"某考点今年出现在选择题→明年仍出现 的概率 {r['next_year_rate']*100:.0f}%")
        print(f"同一考点两次出现的中位间隔 {r['median_gap']} 年，平均 {r['mean_gap']} 年")
        top = sorted(((len(ys), n, ys) for n, ys in r["obj"].items()), reverse=True)[:15]
        print("选择题最常回访的考点：")
        for cnt, n, ys in top:
            print(f"   {n:14} {cnt} 个年份  {ys}")
        print()

    json.dump(report, open(os.path.join(ROOT, "data", "recurrence.json"), "w", encoding="utf-8"),
              ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()

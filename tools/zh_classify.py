SUBJ_MAP = {
    "法理学": JURISPRUDENCE,
    "中国宪法学": CONSTITUTION,
    "中国法制史": LEGAL_HISTORY,
}


def clean_for_match(text, subject):
    if subject == "法理学":
        text = re.sub(r"《[^》]{2,40}》[^。]{0,20}?规定[:：]?", " ", text)
    return re.sub(r"\s+", "", text)


def tag_question(q):
    lexicon = SUBJ_MAP[q["subject"]]
    stem = clean_for_match(q["stem"], q["subject"])
    opts = clean_for_match(" ".join(q.get("options", {}).values()), q["subject"])
    # 优先用题干命中（避免干扰项把汉代题目带到明代），再综合题干+选项
    for text in (stem, stem + " " + opts):
        for node, kws in lexicon:
            for kw in kws:
                if kw in text:
                    return node, kw
    return "未分类", ""


def main():
    import sys
    sys.path.insert(0, os.path.join(ROOT, "tools"))
    from zh_clean_questions import load_clean_questions

    if os.path.exists(TAGGED_PATH):
        os.remove(TAGGED_PATH)
    qs = load_clean_questions(include_subjective=True)

    overrides = {}
    if os.path.exists(OVERRIDES_PATH):
        overrides = json.load(open(OVERRIDES_PATH, encoding="utf-8"))

    out = []
    unmatched = defaultdict(list)
    for q in qs:
        qid = q["id"]
        if qid in overrides:
            node, hit = overrides[qid], "manual"
        else:
            node, hit = tag_question(q)
        if node == "未分类":
            unmatched[q["subject"]].append(q)
        out.append({
            "year": q["year"],
            "num": q["num"],
            "subject": q["subject"],
            "type": q["type"],
            "score": q["score"],
            "stem": q["stem"],
            "options": q["options"],
            "node": node,
            "hit": hit,
        })

    json.dump(out, open(TAGGED_PATH, "w", encoding="utf-8"), ensure_ascii=False, indent=1)

    for subj in ("法理学", "中国宪法学", "中国法制史"):
        sub_qs = [x for x in out if x["subject"] == subj]
        c = Counter(x["node"] for x in sub_qs)
        tot = sum(x["score"] for x in sub_qs)
        obj_cnt = sum(1 for x in sub_qs if x["type"] in ("单项选择", "多项选择"))
        print(f"\n=== {subj} ({len(sub_qs)} 题 / {obj_cnt} 客观, 总 {tot} 分) ===")
        for node, n in c.most_common():
            sc = sum(x["score"] for x in sub_qs if x["node"] == node)
            print(f"  {node:22s} {n:4d} 题  {sc:5d} 分")
        if unmatched[subj]:
            print(f"  未分类 {len(unmatched[subj])} 题:")
            for q in unmatched[subj]:
                print(f"    {q['id']} ({q['type']}): {q['stem'][:75]}")


if __name__ == "__main__":
    main()

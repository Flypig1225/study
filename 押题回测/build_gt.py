ART_RE = re.compile(r'(刑法|民法典|民法通则|民法总则|物权法|合同法|侵权责任法|担保法|婚姻法|继承法)[》]?\s*第\s*(\d+)\s*条')

def extract_article(stem):
    m = ART_RE.search(stem or '')
    if m:
        return f'{m.group(1)}第{m.group(2)}条'
    return None

def build():
    t398 = json.load(open(os.path.join(BASE, 'data/tagged.json')))
    subj398 = [dict(q) for q in t398 if q.get('type') in ('简答', '法条分析', '案例分析', '辨析')]
    for q in subj398:
        key = (q['year'], q['num'])
        man = XINGFA_MANUAL_HIT.get(key) if q['subject'] == '刑法' else MINFA_MANUAL_HIT.get(key)
        if q.get('hit', 'manual') in ('manual', None, ''):
            q['hit'] = man or ''
        art = extract_article(q.get('stem', ''))
        if q['type'] == '法条分析' and art:
            q['article'] = art
        if q['type'] == '法条分析' and not q.get('hit'):
            q['hit'] = art or ''
    gt398 = sorted(subj398, key=lambda q: (q['year'], q['subject'], q['num']))

    t498 = json.load(open(os.path.join(BASE, 'data/zonghe/tagged.json')))
    subj498 = [dict(q) for q in t498 if q.get('type') in ('简答', '分析', '论述')]
    for q in subj498:
        key = (q['year'], q['num'])
        if key in ZONGHE_DYNASTY_FIX and q['subject'] == '中国法制史':
            q['node'] = ZONGHE_DYNASTY_FIX[key]
            q['_dyn_fixed'] = True
        if key in ZONGHE_MANUAL_HIT:
            q['hit'] = ZONGHE_MANUAL_HIT[key]
        elif not q.get('hit') or q.get('hit') == 'manual':
            q['hit'] = ''
    gt498 = sorted(subj498, key=lambda q: (q['year'], q['subject'], q['num']))

    json.dump(gt398, open(os.path.join(OUT, 'gt_398.json'), 'w'), ensure_ascii=False, indent=1)
    json.dump(gt498, open(os.path.join(OUT, 'gt_498.json'), 'w'), ensure_ascii=False, indent=1)
    print('gt398:', len(gt398), 'gt498:', len(gt498))
    # 汇总检查
    for name, gt in (('398', gt398), ('498', gt498)):
        cnt = collections.Counter((q['year']) for q in gt)
        years = sorted(cnt)
        print(name, years[0], '-', years[-1], '每年题数样例:', [cnt[y] for y in years[:5]])
    arts = [(q['year'], q['subject'], q.get('article')) for q in gt398 if q['type'] == '法条分析']
    print('法条分析条目数:', len(arts), '重复:', [a for a, c in collections.Counter(x[2] for x in arts).items() if c > 1])

if __name__ == '__main__':
    build()
